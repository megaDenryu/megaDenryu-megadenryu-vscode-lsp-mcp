// 起点から行内の他位置に交互に拡散する index 列を返す純関数。
// 識別子境界補正で「prepareRename が起点で失敗した場合に同行内の近傍位置を試す」
// 用途で使う。起点に近い位置から順に試すので、識別子の端や直近の識別子に
// 早く当たる。
//
// 例: 起点=5, 行長=10 → [4, 6, 3, 7, 2, 8, 1, 9, 0]
//     (起点 5 自身は除外、両端 0 と 9 まで網羅)

export function 周辺オフセット列を生成する(
  起点: number,
  行長: number,
): number[] {
  const 結果: number[] = [];
  if (行長 <= 0) return 結果;

  for (let 距離 = 1; ; 距離++) {
    const 前 = 起点 - 距離;
    const 後 = 起点 + 距離;
    const 前有効 = 前 >= 0 && 前 < 行長;
    const 後有効 = 後 >= 0 && 後 < 行長;
    if (!前有効 && !後有効) break;
    if (前有効) 結果.push(前);
    if (後有効) 結果.push(後);
  }
  return 結果;
}
