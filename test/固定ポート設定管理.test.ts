import { describe, expect, it } from "vitest";
import type { ポート割当結果 } from "../src/shared/固定ポート割当";
import { 固定ポート設定管理 } from "../src/extension/固定ポート設定管理";

function 管理を作る(
  初期設定: number | undefined,
  初回結果: ポート割当結果,
  手動結果: ポート割当結果 = 初回結果,
) {
  let 保存値 = 初期設定;
  const 保存履歴: number[] = [];
  const 管理 = new 固定ポート設定管理(
    {
      初回割当する: async () => 初回結果,
      既存設定を登録する: async () => 初回結果,
      手動変更する: async () => 手動結果,
    },
    () => ({
      ワークスペース名: "試験",
      ワークスペースファイル: null,
      ワークスペースフォルダ群: ["C:\\devs\\Test"],
    }),
    () => 保存値,
    async (ポート) => {
      保存値 = ポート;
      保存履歴.push(ポート);
    },
  );
  return {
    管理,
    保存履歴,
    設定値を外部変更する: (ポート: number) => {
      保存値 = ポート;
    },
  };
}

describe("固定ポート設定管理", () => {
  it("未設定なら初回割当をワークスペース設定へ保存する", async () => {
    const { 管理, 保存履歴 } = 管理を作る(undefined, {
      種別: "確定",
      ポート: 17800,
      新規割当: true,
    });

    expect(await 管理.初期化する()).toEqual({
      種別: "確定",
      ポート: 17800,
      変更あり: true,
    });
    expect(保存履歴).toEqual([17800]);
    expect(管理.設定を取得する()).toEqual({
      種別: "固定",
      ポート: 17800,
    });
  });

  it("競合する設定ファイル変更を以前の値へ戻す", async () => {
    const 構成 = 管理を作る(
      17800,
      { 種別: "確定", ポート: 17800, 新規割当: false },
      { 種別: "競合", 理由: "割当済み" },
    );
    await 構成.管理.初期化する();
    構成.設定値を外部変更する(19000);

    expect(await 構成.管理.設定ファイル変更を反映する()).toEqual({
      種別: "競合",
      理由: "割当済み",
    });
    expect(構成.保存履歴).toEqual([17800]);
  });

  it("自身が保存した設定変更イベントを処理済みと判定する", async () => {
    const 構成 = 管理を作る(undefined, {
      種別: "確定",
      ポート: 17800,
      新規割当: true,
    });
    await 構成.管理.初期化する();

    expect(構成.管理.保存設定が現在値か()).toBe(true);
  });

  it("初期設定が他ワークスペースと競合する間は起動を禁止する", async () => {
    const 構成 = 管理を作る(17800, {
      種別: "競合",
      理由: "別ワークスペースへ割当済み",
    });

    await 構成.管理.初期化する();

    expect(構成.管理.起動禁止理由を取得する()).toBe(
      "別ワークスペースへ割当済み",
    );
  });

  it("競合後に固定ポートを変更できれば起動禁止を解除する", async () => {
    const 構成 = 管理を作る(
      17800,
      { 種別: "競合", 理由: "別ワークスペースへ割当済み" },
      { 種別: "確定", ポート: 19000, 新規割当: false },
    );
    await 構成.管理.初期化する();

    await 構成.管理.手動変更する(19000);

    expect(構成.管理.起動禁止理由を取得する()).toBeUndefined();
    expect(構成.管理.設定を取得する().ポート).toBe(19000);
  });
});
