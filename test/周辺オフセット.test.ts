import { describe, expect, it } from "vitest";
import { 周辺オフセット列を生成する } from "../src/extension/周辺オフセット";

describe("周辺オフセット列を生成する", () => {
  it("起点 5 / 行長 10 → 前後交互で 9 件", () => {
    expect(周辺オフセット列を生成する(5, 10)).toEqual([4, 6, 3, 7, 2, 8, 1, 9, 0]);
  });

  it("起点 0 (左端) → 右側のみ", () => {
    expect(周辺オフセット列を生成する(0, 5)).toEqual([1, 2, 3, 4]);
  });

  it("起点 4 (右端) → 左側のみ", () => {
    expect(周辺オフセット列を生成する(4, 5)).toEqual([3, 2, 1, 0]);
  });

  it("行長 0 なら空配列", () => {
    expect(周辺オフセット列を生成する(5, 0)).toEqual([]);
  });

  it("起点が行長を大きく超える場合は空配列 (距離 1 で既に両端範囲外)", () => {
    // 起点 10、行長 3 → 距離 1: 前=9 / 後=11 ともに 0..3 範囲外 → break
    // 設計判断: 周辺オフセット列は「起点周辺の探索」を意図しており、起点が大幅に
    // 範囲外なら探索対象なしとする。呼び出し側で起点を行長以内にクリップする
    // 責務とする。
    expect(周辺オフセット列を生成する(10, 3)).toEqual([]);
  });

  it("起点が負値で大きく外れる場合も空配列", () => {
    expect(周辺オフセット列を生成する(-2, 3)).toEqual([]);
  });

  it("起点 = 行長/2、行長 3 → [1, 2, 0]", () => {
    expect(周辺オフセット列を生成する(1, 3)).toEqual([0, 2]);
  });
});
